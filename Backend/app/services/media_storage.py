"""Private report-media storage with local, HTTP API, and legacy S3 adapters."""

from __future__ import annotations

import hashlib
import json
import logging
import os
import time
import uuid
from datetime import datetime, timezone
from email.utils import parsedate_to_datetime
from pathlib import Path
from typing import BinaryIO
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlsplit
from urllib.request import Request, urlopen

from app.config import settings

logger = logging.getLogger(__name__)

HTTP_PUT_MAX_ATTEMPTS = 4
HTTP_PUT_BASE_DELAY_SECONDS = 0.5
HTTP_PUT_MAX_DELAY_SECONDS = 5.0
HTTP_ERROR_BODY_LOG_LIMIT = 1000


class MediaStorageHTTPError(RuntimeError):
    """An upstream HTTP failure with bounded, non-secret diagnostics."""

    def __init__(
        self,
        *,
        status_code: int,
        method: str,
        attempts: int,
        endpoint_host: str,
        response_body: str,
        response_headers: dict[str, str],
    ) -> None:
        self.status_code = status_code
        self.method = method
        self.attempts = attempts
        self.endpoint_host = endpoint_host
        self.response_body = response_body
        self.response_headers = response_headers

        message = (
            f"HTTP media storage at {endpoint_host} returned status {status_code} "
            f"after {attempts} {method} attempt(s)"
        )
        if response_body:
            message += f"; upstream response body: {response_body}"
        if response_headers:
            header_details = ", ".join(f"{name}={value}" for name, value in response_headers.items())
            message += f"; upstream headers: {header_details}"
        super().__init__(message)


def _safe_http_error_details(exc: HTTPError) -> tuple[str, dict[str, str]]:
    try:
        body = exc.read(HTTP_ERROR_BODY_LOG_LIMIT + 1).decode("utf-8", errors="replace")
    finally:
        exc.close()
    body = " ".join("".join(char for char in body if char.isprintable() or char in "\t\n\r").split())
    if len(body) > HTTP_ERROR_BODY_LOG_LIMIT:
        body = f"{body[:HTTP_ERROR_BODY_LOG_LIMIT]}…[truncated]"

    diagnostic_header_names = (
        "Content-Type",
        "Retry-After",
        "Server",
        "Via",
        "X-Request-ID",
        "X-RateLimit-Limit",
        "X-RateLimit-Remaining",
        "X-RateLimit-Reset",
    )
    headers = {}
    for name in diagnostic_header_names:
        value = exc.headers.get(name) if exc.headers else None
        if value is not None:
            headers[name] = " ".join(
                "".join(char for char in str(value) if char.isprintable()).split()
            )[:200]
    return body, headers


def _s3_client():
    try:
        import boto3
        from botocore.config import Config
    except ImportError as exc:  # pragma: no cover - deployment configuration
        raise RuntimeError("S3 media storage requires boto3") from exc

    return boto3.client(
        "s3",
        region_name=settings.media_s3_region or None,
        endpoint_url=settings.media_s3_endpoint_url or None,
        aws_access_key_id=settings.media_s3_access_key_id or None,
        aws_secret_access_key=settings.media_s3_secret_access_key or None,
        aws_session_token=settings.media_s3_session_token or None,
        config=Config(s3={"addressing_style": settings.media_s3_addressing_style}),
    )


def _local_path(key: str) -> Path:
    # Keys are generated by this module; still reject traversal defensively.
    if not key or Path(key).is_absolute() or ".." in Path(key).parts:
        raise ValueError("Invalid media storage key")
    return Path(settings.media_storage_path).resolve() / key


def new_storage_key() -> str:
    return f"reports/{uuid.uuid4().hex}"


def _http_put_retry_delay(retry_after: str | None, retry_index: int) -> float:
    delay = None
    if retry_after:
        try:
            delay = float(retry_after)
        except ValueError:
            try:
                retry_at = parsedate_to_datetime(retry_after)
                if retry_at.tzinfo is None:
                    retry_at = retry_at.replace(tzinfo=timezone.utc)
                delay = (retry_at - datetime.now(timezone.utc)).total_seconds()
            except (TypeError, ValueError, OverflowError):
                pass

    if delay is None:
        delay = HTTP_PUT_BASE_DELAY_SECONDS * (2**retry_index)
    return min(max(delay, 0.0), HTTP_PUT_MAX_DELAY_SECONDS)


def _http_request(key: str, method: str, data: bytes | None = None, content_type: str | None = None) -> bytes:
    endpoint = settings.media_storage_api_url.rstrip("/")
    token = settings.media_storage_api_key
    if not endpoint or not token:
        raise RuntimeError("HTTP media storage requires MEDIA_STORAGE_API_URL and MEDIA_STORAGE_API_KEY")
    endpoint_parts = urlsplit(endpoint)
    if (
        endpoint_parts.scheme not in {"http", "https"}
        or not endpoint_parts.hostname
        or endpoint_parts.query
        or endpoint_parts.fragment
    ):
        raise RuntimeError("MEDIA_STORAGE_API_URL must be an HTTP(S) URL")

    url = f"{endpoint_parts.geturl()}/internal/objects/{quote(key, safe='/')}"
    headers = {"Authorization": f"Bearer {token}"}
    if content_type:
        headers["Content-Type"] = content_type
    max_attempts = HTTP_PUT_MAX_ATTEMPTS if method == "PUT" else 1
    for attempt in range(max_attempts):
        request = Request(url, data=data, headers=headers, method=method)
        try:
            with urlopen(request, timeout=120) as response:
                return response.read()
        except HTTPError as exc:
            if method == "PUT" and exc.code == 429 and attempt + 1 < max_attempts:
                delay = _http_put_retry_delay(exc.headers.get("Retry-After"), attempt)
                logger.warning(
                    "HTTP media storage rate-limited an upload; retrying attempt %d/%d in %.1f seconds",
                    attempt + 2,
                    max_attempts,
                    delay,
                )
                exc.close()
                time.sleep(delay)
                continue
            response_body, response_headers = _safe_http_error_details(exc)
            raise MediaStorageHTTPError(
                status_code=exc.code,
                method=method,
                attempts=attempt + 1,
                endpoint_host=endpoint_parts.hostname,
                response_body=response_body,
                response_headers=response_headers,
            ) from exc
        except URLError as exc:
            raise RuntimeError("Could not reach the HTTP media storage service") from exc

    raise RuntimeError("HTTP media storage upload retry loop ended unexpectedly")


def put_object(key: str, data: bytes, content_type: str) -> None:
    if settings.media_storage_backend == "http":
        response = json.loads(_http_request(key, "PUT", data, content_type))
        if (
            response.get("key") != key
            or response.get("size") != len(data)
            or response.get("sha256") != hashlib.sha256(data).hexdigest()
        ):
            raise RuntimeError("HTTP media storage upload verification failed")
        return
    if settings.media_storage_backend == "s3":
        args = {"Bucket": settings.media_s3_bucket, "Key": key, "Body": data, "ContentType": content_type}
        if settings.media_s3_sse:
            args["ServerSideEncryption"] = settings.media_s3_sse
        if settings.media_s3_kms_key_id:
            args["SSEKMSKeyId"] = settings.media_s3_kms_key_id
        _s3_client().put_object(**args)
        return

    path = _local_path(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
    try:
        with temporary.open("xb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def get_object(key: str, backend: str | None = None) -> bytes:
    backend = backend or settings.media_storage_backend
    if backend == "http":
        return _http_request(key, "GET")
    if backend == "s3":
        response = _s3_client().get_object(Bucket=settings.media_s3_bucket, Key=key)
        body: BinaryIO = response["Body"]
        try:
            return body.read()
        finally:
            body.close()
    return _local_path(key).read_bytes()


def delete_object(key: str, backend: str | None = None) -> None:
    backend = backend or settings.media_storage_backend
    if backend == "http":
        _http_request(key, "DELETE")
        return
    if backend == "s3":
        # S3 delete is idempotent, which makes the retry queue safe.
        _s3_client().delete_object(Bucket=settings.media_s3_bucket, Key=key)
        return
    _local_path(key).unlink(missing_ok=True)
